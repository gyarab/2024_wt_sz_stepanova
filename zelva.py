from turtle import forward, left, shape, exitonclick

from math import sqrt
delka = sqrt(2)*50

forward(100)

forward(100)
shape('turtle')
left(90)
forward(100)
left(45)
forward(delka)
left(90)
forward(delka)
left(45)
forward(100)
left(135)
forward(delka*2)
left(135)
forward(100)
left(135)
forward(delka*2)

exitonclick
